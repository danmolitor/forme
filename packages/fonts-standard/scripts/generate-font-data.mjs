// Generates src/generated/font-data.ts — the 12 Liberation TTFs embedded as
// base64 so the library returns Uint8Array buffers with no file IO (works in
// Node, WASM, and the browser). Run by `npm run build` before tsc; the output
// is gitignored (regenerated from fonts/*.ttf, the tracked source of truth).
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const fontsDir = join(here, '..', 'fonts');
const outFile = join(here, '..', 'src', 'generated', 'font-data.ts');

const files = readdirSync(fontsDir).filter((f) => f.endsWith('.ttf')).sort();
let out =
  '// GENERATED by scripts/generate-font-data.mjs — do not edit.\n' +
  '// The 12 Liberation TTFs (SIL OFL 1.1) embedded as base64.\n\n';

const keys = [];
for (const file of files) {
  const key = file.replace(/\.ttf$/, '').replace(/-/g, '_');
  keys.push([key, file]);
  const b64 = readFileSync(join(fontsDir, file)).toString('base64');
  out += `const ${key} = '${b64}';\n`;
}

out += '\n/** Base64-encoded TTF bytes, keyed by font file stem. */\n';
out += 'export const FONT_DATA_BASE64: Record<string, string> = {\n';
for (const [key, file] of keys) {
  out += `  '${file.replace(/\.ttf$/, '')}': ${key},\n`;
}
out += '};\n';

writeFileSync(outFile, out);
console.log(`generated ${outFile} from ${files.length} fonts`);
